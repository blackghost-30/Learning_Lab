#include <iostream>
using namespace std;

int main1()
{
	// 1. 短整型（-32768 ~ 32767）
	short num1 = 10;

	// 2. 整形
	int num2 = 10;

	// 3. 长整型
	long num3 = 10;

	// 4. 长长整形
	long long num4 = 10;

	cout << "num1 = " << num1 << endl;
	cout << "num2 = " << num1 << endl;
	cout << "num3 = " << num1 << endl;
	cout << "num4 = " << num1 << endl;

	system("pause");

	return 0;
}